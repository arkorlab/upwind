import type { BuildPaths } from './build-paths.ts';
import { jsLiteral } from './codegen.ts';
import type { EntryModule } from './function.ts';

/**
 * Keep every route lazy. An external output's route module is normalized once, on its first
 * load, so Next.js reads its manifests from the same VFS mount the adapter gives them.
 */
export function appEntrySource(
  entries: readonly EntryModule[],
  paths: Pick<BuildPaths, 'external' | 'runtimeDistDir'>,
): string {
  const table = entries
    .map((entry) => {
      const key = jsLiteral(entry.id);
      const file = jsLiteral(entry.filePath);
      if (!paths.external) return `  ${key}: () => require(${file}),`;
      return [
        `  ${key}: (() => {`,
        '    let entry;',
        '    const normalize = (loaded) => {',
        '      if (loaded.routeModule !== undefined) {',
        `        loaded.routeModule.distDir = ${jsLiteral(paths.runtimeDistDir)};`,
        '      }',
        '      return loaded;',
        '    };',
        '    return () => {',
        '      if (entry === undefined) {',
        `        const loaded = require(${file});`,
        '        entry = typeof loaded?.then === "function"',
        '          ? Promise.resolve(loaded).then(normalize).catch((error) => {',
        '              entry = undefined;',
        '              throw error;',
        '            })',
        '          : normalize(loaded);',
        '      }',
        '      return entry;',
        '    };',
        '  })(),',
      ].join('\n');
    })
    .join('\n');
  return [
    '// Generated by @stayingupwind/adapter: the entrypoints `next build` produced, by route.',
    'module.exports = {',
    '  entries: {',
    table,
    '  },',
    '};',
    '',
  ].join('\n');
}

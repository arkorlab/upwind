import {
  dynamicRouteFor,
  type ProjectManifest,
  type RouteEntry,
} from '@stayingupwind/core/manifest';
import { allowRecoveryScript } from '@stayingupwind/core/request';
import { GATE_RESUME_HEADER } from '@stayingupwind/host/bindings';
import type { ResolvedPolicy } from '@stayingupwind/host/delivery';
import { RECOVERY_SCRIPT_CSP_SOURCE } from '@stayingupwind/host/splice';

import { ownRecordEntry } from '../cache/member.ts';
import type { EdgeContext } from '../strategies/context.ts';
import type { ServedGeneration } from './document-delivery.ts';
import { type DocumentInput, handleDocument } from './document.ts';
import type { GateShellDirective } from './gate.ts';
import { bypassed, offTheEdge, requestAsLeft } from './hosted-route.ts';
import type { MiddlewareSkipped } from './middleware.ts';

/**
 * A document of a route its gate answered with a shell of its own (`GATE_SHELL`), served as the
 * route's runtime cache serves a generation: the shell's bytes first, then what the route's Function
 * renders from the postponed state, resumed as the route the shell names — through the same
 * composition, the splice and its recovery, a nonce minted for the response, the coding chosen on
 * the way out. Nothing else is read for it: no record, no shell of the build's, no rendering of one.
 * Nothing is regenerated for it, and nothing of it is kept: no read of a record is reported, and the
 * document, completed for one visitor, goes out `private, no-store` as every resumed one does.
 *
 * Where the edge would hand the route's document to its Function whole — a route off the edge, a
 * request Next.js serves no prerender to (`bypassed`), a policy that blocks the recovery script —
 * the gate's shell is handed on the same way, and the Function renders the page itself.
 */

/** What a gate's shell is reported as having come from: `src=gen-gate` on `x-arkor-edge`. */
const GATE_SOURCE = 'gate';
/**
 * The digest a gate's shell goes as: none a build's shell has, so no rendering of the build's — its
 * bytes compressed ahead — ever goes out in place of a gate's (`usableRendering`).
 */
const NO_BUILD_DIGEST = '';
const CSP_HEADER = 'content-security-policy';
/** No middleware runs for a gated route: a build with one declares no gate (`gateIssues`). */
const NO_MIDDLEWARE: MiddlewareSkipped = { kind: 'skipped', reason: 'unmatched' };
/** Why a route whose prerender Next.js would not serve the request goes to the Function. */
const BYPASS_FOR = 'bypass-for';
/** A navigation whose pathname names no route the build proved (`classifyRequest`). */
const ROUTE_NOT_PROVED = 'route-not-proved';
const APP_PAGE = 'app-page';

export interface GateShellInput {
  readonly request: Request<unknown, IncomingRequestCfProperties>;
  readonly url: URL;
  readonly manifest: ProjectManifest;
  /** The route the request was classified as a document of. */
  readonly entry: RouteEntry;
  /** The headers the request was classified on, which the route's conditions are judged on. */
  readonly classifiedHeaders: Headers;
  readonly edge: EdgeContext;
  readonly resolved: ResolvedPolicy<EdgeContext>;
  readonly directive: GateShellDirective;
  /** Hand the request to the application's Function, as every passthrough of it goes. */
  readonly passthrough: DocumentInput['passthrough'];
}

/**
 * A gate's shell as a document's delivery reads a generation: its bytes the shell, of the path the
 * visitor asked for (`pathname`), its state what the runtime resumes as the route it names, its
 * headers replayed as a generation's are — the recovery script permitted by a policy among them,
 * as a record's is as it is read (`generation-loader.ts`) — and the gate's token told the resume
 * beside its request. Never fresh or stale to the edge, which judges nothing of it; read from
 * nowhere, and regenerated by nobody.
 */
export function gateGeneration(directive: GateShellDirective, pathname: string): ServedGeneration {
  const { header, html, postponed } = directive.shell;
  const { resume } = header;
  return {
    pack: {
      header: {
        pathname,
        seq: header.seq,
        source: 'runtime',
        route: header.route,
        headers:
          header.headers[CSP_HEADER] === undefined
            ? header.headers
            : allowRecoveryScript(header.headers, RECOVERY_SCRIPT_CSP_SOURCE),
        htmlSha256: NO_BUILD_DIGEST,
        htmlLength: header.htmlLength,
      },
      html,
      postponed,
    },
    validity: 'unknown',
    source: GATE_SOURCE,
    readBytes: undefined,
    lookupMs: directive.lookupMs,
    member: false,
    regeneration: undefined,
    onServed: undefined,
    gate: {
      name: directive.gate,
      told: resume === undefined ? undefined : { [GATE_RESUME_HEADER]: resume },
    },
  };
}

/** The document a gate's shell is served as, or the Function's where the route's would be. */
export function serveGateShell(input: GateShellInput): Promise<Response> {
  const { edge, entry } = input;
  const off = offTheEdge(edge, entry);
  if (off !== undefined) {
    return input.passthrough(off, NO_MIDDLEWARE, entry.pathname);
  }
  if (bypassed(input, entry, requestAsLeft(input, NO_MIDDLEWARE), NO_MIDDLEWARE)) {
    return input.passthrough(BYPASS_FOR, NO_MIDDLEWARE, entry.pathname);
  }
  return handleDocument({
    request: input.request,
    entry,
    manifest: input.manifest,
    resolved: input.resolved,
    edge,
    middleware: NO_MIDDLEWARE,
    shellRead: undefined,
    generation: gateGeneration(input.directive, input.url.pathname),
    passthrough: input.passthrough,
  });
}

/**
 * The route a gate's shell of a class the build made no shell of is served under, as a member's own
 * record is (`ownRecordEntry`): of a navigation that named no proved route (`unproved`, the reason
 * its classification gave), whose pathname is of the class of the gate's own route
 * (`DynamicRoute.gated`) — its name, its Function and, where the build serves its members from
 * records, the conditions they are passed on under. None of any other request, which the gate's
 * shell is not served for.
 */
export function gatedEntryOf(
  manifest: ProjectManifest,
  request: { readonly url: URL; readonly headers: Headers },
  unproved: string | undefined,
): RouteEntry | undefined {
  if (unproved !== ROUTE_NOT_PROVED) {
    return undefined;
  }
  const dynamic = dynamicRouteFor(manifest, request.url, request.headers);
  const gated = dynamic?.gated;
  // The class of the gate's route, whatever the build made of it: no shell is what it names none.
  if (dynamic === undefined || gated === undefined || (dynamic.route ?? gated) !== gated) {
    return undefined;
  }
  return ownRecordEntry({
    ...dynamic,
    members: dynamic.members ?? { kind: APP_PAGE, route: gated },
  });
}

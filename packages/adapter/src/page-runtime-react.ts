import { readFile } from 'node:fs/promises';

import type { Node, Program } from '@oxc-project/types';
import type { Plugin } from 'rolldown';
import { parseAst } from 'rolldown/parseAst';

/**
 * The middleware's Function, and what of Next.js's page runtime its code reads.
 *
 * Turbopack compiles a Node.js middleware against the same server modules a page is: `NextResponse`
 * and `NextRequest` bring the cookies, the cookies `connection()`, and `connection()` the module
 * that tracks dynamic rendering, which takes React — the React the page runtime vendors for server
 * components, `vendored["react-rsc"].React`. Turbopack leaves the page runtime external and the
 * bundler follows the require, so the middleware's Function carried the whole runtime (664 KB: the
 * renderers, the server components' runtime, and what they bring, `jsonwebtoken` among it) and
 * evaluated it as the middleware loaded, for one object it never renders anything with.
 *
 * In the middleware's Function alone the runtime resolves to a module holding that object and
 * nothing else: the same React, the build Next.js ships of it for server components
 * (`next/dist/compiled/react{,-experimental}/react.react-server.js`, the release the runtime vendors),
 * shaped as the runtime hands it out — a namespace with its `default`. Measured on the minimal
 * fixture's middleware: its code 1,436 → 642 KB, its cold start 25 ms sooner.
 *
 * Only where that is known to be enough. What the middleware's chunks read of the runtime is read off
 * them once the bundle is built (`readsOfPageRuntime`): every require of it has to be the external a
 * server chunk declares for it, and every use of that external — through any module that only
 * re-exports it — the read of `vendored["react-rsc"].React`. A build where it is anything else, or
 * where the chunks are not written as this reads them, is bundled again with the runtime itself.
 */

/** The page runtime as Turbopack names it external, in either release of React. */
const PAGE_RUNTIME =
  /^next\/dist\/compiled\/next-server\/app-page-turbo(?<experimental>-experimental)?\.runtime\.prod\.js$/u;
/** The id the runtime is bundled under in its place; what the dependency record lists it as. */
const ID_PREFIX = 'arkor-page-runtime-react:';
/** A module Turbopack wrote for the server, by the path the bundler read it at. */
const SERVER_CHUNK = /[/\\]server[/\\]chunks[/\\]/u;
/** Turbopack's own names for a require of another module of the build, and for an import of one. */
const MODULE_REQUIRES: ReadonlySet<string> = new Set(['i', 'r']);
/** The one path the middleware's code reads off the runtime, member by member. */
const READ = ['vendored', 'react-rsc', 'React'] as const;

/** A require of the runtime, as the bundler resolved it. */
export interface PageRuntimeRequire {
  readonly specifier: string;
  readonly importer: string | undefined;
}

/** What stands in for the runtime: React, as the runtime vendors it, under the one path read. */
function reactOnlySource(channel: string): string {
  const react = JSON.stringify(`next/dist/compiled/${channel}/react.react-server.js`);
  return [
    '// Generated by @stayingupwind/adapter: of the page runtime, the React it vendors for server',
    '// components, which is all the middleware reads of it.',
    `const React = require(${react});`,
    'const namespace = Object.defineProperty({ ...React, default: React }, "__esModule", { value: true });',
    'module.exports = { vendored: { "react-rsc": { React: namespace } } };',
    '',
  ].join('\n');
}

/** The page runtime resolved to React alone, every require of it kept in `requires`. */
export function pageRuntimeReactPlugin(requires: PageRuntimeRequire[]): Plugin {
  return {
    name: 'arkor-page-runtime-react',
    resolveId: {
      filter: { id: PAGE_RUNTIME },
      handler(source, importer) {
        requires.push({ specifier: source, importer });
        const channel =
          PAGE_RUNTIME.exec(source)?.groups?.['experimental'] === undefined
            ? 'react'
            : 'react-experimental';
        return `${ID_PREFIX}${channel}`;
      },
    },
    load: {
      filter: { id: /^arkor-page-runtime-react:/u },
      handler: (id) => ({ code: reactOnlySource(id.slice(ID_PREFIX.length)), moduleType: 'js' }),
    },
  };
}

function isNode(value: unknown): value is Node {
  return typeof value === 'object' && value !== null && 'type' in value;
}

/** A node on the way down, with the one it hangs from and by which field. */
interface Visit {
  readonly node: Node;
  readonly up: Visit | undefined;
  readonly key: string | undefined;
}

/** The nodes under `visit` — each field that is one, or a list of them — as visits of their own. */
function childrenOf(visit: Visit): Visit[] {
  const children: Visit[] = [];
  for (const [key, value] of Object.entries(visit.node)) {
    // A parent link, when the parser adds one, would lead back up.
    if (key !== 'parent') {
      const values: unknown[] = Array.isArray(value) ? value : [value];
      children.push(
        ...values.filter((child) => isNode(child)).map((node) => ({ node, up: visit, key })),
      );
    }
  }
  return children;
}

/** Every node of `program`, each with its parent. Walked with a stack: a chunk is megabytes. */
function visitsOf(program: Program): Visit[] {
  const visits: Visit[] = [];
  const pending: Visit[] = [{ node: program, up: undefined, key: undefined }];
  for (let visit = pending.pop(); visit !== undefined; visit = pending.pop()) {
    visits.push(visit);
    pending.push(...childrenOf(visit));
  }
  return visits;
}

/** A member's name, written `a.name` or `a["name"]`; nothing for one computed otherwise. */
function memberName(node: Node): string | undefined {
  if (node.type !== 'MemberExpression') {
    return undefined;
  }
  if (!node.computed) {
    return node.property.type === 'Identifier' ? node.property.name : undefined;
  }
  return node.property.type === 'Literal' && typeof node.property.value === 'string'
    ? node.property.value
    : undefined;
}

/** A string literal naming the page runtime. */
function namesRuntime(node: Node | null | undefined): boolean {
  return (
    node?.type === 'Literal' && typeof node.value === 'string' && PAGE_RUNTIME.test(node.value)
  );
}

/** `<context>.<method>(<module id>)`: Turbopack reaching another module of the build by its id. */
function moduleReference(node: Node): { readonly method: string; readonly id: number } | undefined {
  if (node.type !== 'CallExpression' || node.arguments.length !== 1) {
    return undefined;
  }
  const [argument] = node.arguments;
  const { callee } = node;
  if (
    argument?.type !== 'Literal' ||
    typeof argument.value !== 'number' ||
    callee.type !== 'MemberExpression' ||
    callee.computed ||
    callee.object.type !== 'Identifier' ||
    callee.property.type !== 'Identifier'
  ) {
    return undefined;
  }
  return { method: callee.property.name, id: argument.value };
}

/**
 * Whether the call at `visit` is the whole of its module: `<module>.exports = <call>`, the one
 * statement of the factory, as Turbopack writes a module that is an external or a re-export.
 */
function isWholeModule(visit: Visit): boolean {
  const assignment = visit.up;
  const statement = assignment?.up;
  const block = statement?.up;
  const factory = block?.up;
  return (
    assignment?.node.type === 'AssignmentExpression' &&
    assignment.node.operator === '=' &&
    visit.key === 'right' &&
    memberName(assignment.node.left) === 'exports' &&
    statement?.node.type === 'ExpressionStatement' &&
    block?.node.type === 'BlockStatement' &&
    block.node.body.length === 1 &&
    (factory?.node.type === 'ArrowFunctionExpression' ||
      factory?.node.type === 'FunctionExpression')
  );
}

/**
 * `<context>.<method>("<runtime>", () => require("<runtime>"))`, the whole of its module: the
 * external a chunk declares for the runtime, which the module's own require loads when asked.
 */
function isExternalDeclaration(visit: Visit): boolean {
  const { node } = visit;
  if (node.type !== 'CallExpression' || node.arguments.length !== 2) {
    return false;
  }
  const [name, thunk] = node.arguments;
  if (
    name?.type !== 'Literal' ||
    !namesRuntime(name) ||
    thunk?.type !== 'ArrowFunctionExpression' ||
    thunk.params.length > 0
  ) {
    return false;
  }
  const loaded = thunk.body;
  const [loadedName] = loaded.type === 'CallExpression' ? loaded.arguments : [];
  return (
    loaded.type === 'CallExpression' &&
    loaded.callee.type === 'Identifier' &&
    loaded.callee.name === 'require' &&
    loaded.arguments.length === 1 &&
    loadedName?.type === 'Literal' &&
    loadedName.value === name.value &&
    isWholeModule(visit)
  );
}

/** The external declaration a string naming the runtime is part of, if it is part of one. */
function declarationOf(visit: Visit): Visit | undefined {
  // The name the external is declared under: the declaration's first argument.
  if (visit.up !== undefined && isExternalDeclaration(visit.up)) {
    return visit.up;
  }
  // The name its thunk requires: `require(<name>)`, the body of the thunk the declaration takes.
  const thunk = visit.up?.up;
  const declaration = thunk?.up;
  return declaration !== undefined &&
    thunk?.node.type === 'ArrowFunctionExpression' &&
    isExternalDeclaration(declaration)
    ? declaration
    : undefined;
}

/** The module a node is written in: the factory a chunk's table holds, by its id. */
function moduleIdOf(visit: Visit): number | undefined {
  for (let at: Visit = visit; at.up !== undefined; at = at.up) {
    const { node } = at;
    const table = at.up.node;
    if (
      (node.type === 'ArrowFunctionExpression' || node.type === 'FunctionExpression') &&
      table.type === 'ArrayExpression'
    ) {
      const index = table.elements.indexOf(node);
      const id = index > 0 ? table.elements[index - 1] : undefined;
      return id?.type === 'Literal' && typeof id.value === 'number' ? id.value : undefined;
    }
  }
  return undefined;
}

/** Whether the call at `visit` is read as `<call>.vendored["react-rsc"].React` and no other way. */
function readsReactOnly(visit: Visit): boolean {
  let at: Visit = visit;
  for (const member of READ) {
    const { up } = at;
    if (up === undefined || at.key !== 'object' || memberName(up.node) !== member) {
      return false;
    }
    at = up;
  }
  return true;
}

/** A chunk as read for this question: where it is, and every node of it. */
interface ParsedChunk {
  readonly file: string;
  readonly visits: readonly Visit[];
}

/**
 * The modules that are the runtime — each external a chunk declares for it — or why they cannot be
 * told: a chunk that names the runtime anywhere else.
 */
function runtimeExternals(parsed: readonly ParsedChunk[]): {
  readonly ids: Set<number>;
  readonly refusal?: string;
} {
  const ids = new Set<number>();
  for (const { file, visits } of parsed) {
    for (const visit of visits) {
      if (!namesRuntime(visit.node)) {
        continue;
      }
      const declaration = declarationOf(visit);
      const id = declaration === undefined ? undefined : moduleIdOf(declaration);
      if (id === undefined) {
        return {
          ids,
          refusal: `${file} names the page runtime other than in the external a module of its table declares`,
        };
      }
      ids.add(id);
    }
  }
  return { ids };
}

/**
 * The modules that are nothing but a re-export of one in `runtime`, added to it until no more are
 * found; the references that make them, returned to be passed over as uses.
 */
function addReexports(parsed: readonly ParsedChunk[], runtime: Set<number>): Set<Node> {
  const reexports = new Set<Node>();
  for (let grew = true; grew;) {
    grew = false;
    for (const { visits } of parsed) {
      for (const visit of visits) {
        const reference = moduleReference(visit.node);
        if (reference?.method !== 'r' || !runtime.has(reference.id) || !isWholeModule(visit)) {
          continue;
        }
        reexports.add(visit.node);
        const id = moduleIdOf(visit);
        if (id !== undefined && !runtime.has(id)) {
          runtime.add(id);
          grew = true;
        }
      }
    }
  }
  return reexports;
}

/** One bundle of a Function's code: what it required of the page runtime, and what it stubbed. */
export interface PageRuntimeBundle {
  readonly pageRuntime: readonly PageRuntimeRequire[];
  readonly sinks: { readonly stubs: string[] };
}

/**
 * The middleware's Function's code, bundled with the page runtime as React alone where its chunks
 * (`chunks`) read nothing more of it, and with the runtime itself where they do. `write` bundles it
 * once, as React alone when told to; the runtime bundled so is listed among its stubs.
 */
export async function withPageRuntimeAsReact<T extends PageRuntimeBundle>(
  write: (reactOnly: boolean) => Promise<T>,
  chunks: readonly string[],
): Promise<T> {
  const built = await write(true);
  if (built.pageRuntime.length === 0) {
    return built;
  }
  if ((await readsOfPageRuntime(built.pageRuntime, chunks)) !== undefined) {
    return write(false);
  }
  built.sinks.stubs.push(...new Set(built.pageRuntime.map((required) => required.specifier)));
  return built;
}

/**
 * Why the page runtime cannot be React alone in this Function, or nothing where it can: every
 * require of it (`requires`) and every use of it in the server chunks the Function carries
 * (`chunks`), as the module comment says.
 */
export async function readsOfPageRuntime(
  requires: readonly PageRuntimeRequire[],
  chunks: readonly string[],
): Promise<string | undefined> {
  for (const { specifier, importer } of requires) {
    if (importer === undefined || !SERVER_CHUNK.test(importer)) {
      return `${importer ?? 'the entry'} requires ${specifier} other than as a chunk's external`;
    }
  }
  const parsed: ParsedChunk[] = await Promise.all(
    chunks.map(async (file) => {
      const source = await readFile(file, 'utf8');
      return { file, visits: visitsOf(parseAst(source, { lang: 'js' }, file)) };
    }),
  );
  const { ids: runtime, refusal } = runtimeExternals(parsed);
  if (refusal !== undefined) {
    return refusal;
  }
  if (runtime.size === 0) {
    return 'no server chunk declares the page runtime it requires';
  }
  const reexports = addReexports(parsed, runtime);
  for (const { file, visits } of parsed) {
    for (const visit of visits) {
      const reference = moduleReference(visit.node);
      if (reference === undefined || !runtime.has(reference.id) || reexports.has(visit.node)) {
        continue;
      }
      if (!MODULE_REQUIRES.has(reference.method) || !readsReactOnly(visit)) {
        return `${file} reads more of the page runtime (module ${String(reference.id)}) than vendored["react-rsc"].React`;
      }
    }
  }
  return undefined;
}

import { readFile, writeFile } from 'node:fs/promises';
import path from 'node:path';

import { jsLiteral } from './codegen.ts';
import type { EdgeEntry } from './edge.ts';
import { exists } from './fs.ts';

/** The project's Edge hook is already compiled by Next.js; the host must not substitute its Node hook. */
export interface EdgeInstrumentation {
  readonly module: string;
  readonly files: readonly string[];
  readonly own: boolean;
}

const MODULE_NAME = 'edge-instrumentation.cjs';
const ENTRY = 'middleware_instrumentation';

/** Edge hosts are an explicit opt-in; Node hosts and generated Workflow registrations are not inherited. */
export function checkedEdgeInstrumentationModules(value: unknown): readonly string[] {
  if (value === undefined) return [];
  if (
    !Array.isArray(value) ||
    !value.every(
      (file: unknown): file is string =>
        typeof file === 'string' && path.isAbsolute(file) && !file.includes('\0'),
    )
  ) {
    throw new TypeError(
      '@stayingupwind/adapter: edgeInstrumentationModules must be absolute module paths',
    );
  }
  return [...value];
}

/**
 * Install before evaluating any Edge chunks. Next.js eagerly caches this registry entry while
 * evaluating next/server, which the project's hook may itself import. The temporary accessor
 * captures Next.js's original assignment while every reader sees the composed promise. It is
 * replaced by an ordinary data property once the hook's files have been evaluated.
 */
export function edgeInstrumentationSource(hosts: readonly string[], own: boolean): string {
  return [
    '// Generated by @stayingupwind/adapter: host and project Edge instrumentation.',
    'module.exports = function install(registry) {',
    `  const key = ${jsLiteral(ENTRY)};`,
    '  if (Object.hasOwn(registry, key)) {',
    "    throw new Error('@stayingupwind/adapter: Edge instrumentation was loaded before composition');",
    '  }',
    '  let original;',
    '  let assignments = 0;',
    '  let failed = false;',
    '  let failure;',
    '  let finish;',
    '  const loaded = new Promise((resolve) => { finish = resolve; });',
    '  let hosts;',
    '  const composed = loaded.then(async () => {',
    '    if (failed) throw failure;',
    '    const own = await original;',
    ...(own
      ? [
          "    if (own === null || (typeof own !== 'object' && typeof own !== 'function')) {",
          "      throw new Error('@stayingupwind/adapter: the Edge instrumentation entry is not a module');",
          '    }',
        ]
      : []),
    '    async function call(hook, args) {',
    '      for (const host of hosts) {',
    "        if (typeof host?.[hook] === 'function') {",
    '          try { await host[hook](...args); }',
    '          catch (error) { console.error("upwind: the host\'s " + hook + " failed", error); }',
    '        }',
    '      }',
    "      if (typeof own?.[hook] === 'function') return own[hook](...args);",
    '      return undefined;',
    '    }',
    '    let registration;',
    '    return {',
    '      ...own,',
    '      register(...args) {',
    "        registration ??= call('register', args);",
    '        return registration;',
    '      },',
    "      onRequestError(...args) { return call('onRequestError', args); },",
    '    };',
    '  });',
    // Keep the rejection available to Next's awaited loader without an unhandled orphan on a
    // synchronous chunk-evaluation failure that aborts before Next gets as far as invoking it.
    '  composed.catch(() => {});',
    '  Object.defineProperty(registry, key, {',
    '    configurable: true, enumerable: true,',
    '    get() { return composed; },',
    '    set(value) { original = value; assignments += 1; },',
    '  });',
    '  hosts = [',
    ...hosts.map((host) => {
      return [
        '    (() => {',
        `      try { return require(${jsLiteral(host)}); }`,
        '      catch (error) { console.error("upwind: a host\'s instrumentation could not be loaded", error); }',
        '      return undefined;',
        '    })(),',
      ].join('\n');
    }),
    '  ];',
    '  function release() {',
    '    try {',
    '      Object.defineProperty(registry, key, {',
    '        value: composed, configurable: true, enumerable: true, writable: true,',
    '      });',
    '    } finally { finish(); }',
    '  }',
    '  return {',
    '    finish() {',
    `      if (assignments !== ${own ? '1' : '0'}) {`,
    '        failed = true;',
    "        failure = new Error('@stayingupwind/adapter: unexpected Edge instrumentation registration count: ' + assignments);",
    '      }',
    '      release();',
    '      if (failed) throw failure;',
    '    },',
    '    fail(error) {',
    '      failed = true;',
    '      failure = error;',
    '      try { release(); }',
    "      catch (cleanup) { console.error('upwind: Edge instrumentation cleanup failed', cleanup); }",
    '    },',
    '  };',
    '};',
    '',
  ].join('\n');
}

function refused(): never {
  throw new Error('@stayingupwind/adapter: unsupported Edge instrumentation manifest');
}

/** Only the known Turbopack instrumentation manifest shape is accepted when host hooks are added. */
export function edgeInstrumentationFiles(raw: unknown, distDir: string): string[] {
  if (typeof raw !== 'object' || raw === null || !('instrumentation' in raw)) return refused();
  const own = raw.instrumentation;
  if (typeof own !== 'object' || own === null || !('files' in own) || !Array.isArray(own.files)) {
    return refused();
  }
  if (own.files.length === 0) return refused();
  return own.files.map((file: unknown) => {
    if (typeof file !== 'string' || !file.endsWith('.js') || path.isAbsolute(file))
      return refused();
    const absolute = path.resolve(distDir, file);
    const relative = path.relative(distDir, absolute);
    if (relative.startsWith('..') || path.isAbsolute(relative)) return refused();
    return absolute;
  });
}

/** Add nothing to builds without hosts or Edge entries, including their existing load order. */
export async function edgeInstrumentationOf(input: {
  readonly distDir: string;
  readonly outDir: string;
  readonly hosts: readonly string[];
  readonly entries: readonly EdgeEntry[];
}): Promise<EdgeInstrumentation | undefined> {
  if (input.hosts.length === 0 || input.entries.length === 0) return undefined;
  const manifest = path.join(
    input.distDir,
    'server',
    'instrumentation',
    'middleware-manifest.json',
  );
  const own =
    (await exists(path.join(input.distDir, 'server', 'instrumentation.js'))) ||
    (await exists(manifest));
  const files = own
    ? edgeInstrumentationFiles(JSON.parse(await readFile(manifest, 'utf8')), input.distDir)
    : [];
  for (const entry of input.entries) {
    if (files.some((file, index) => entry.files[index] !== file)) {
      throw new Error(
        '@stayingupwind/adapter: an Edge output does not begin with its instrumentation files',
      );
    }
  }
  const module = path.join(input.outDir, MODULE_NAME);
  await writeFile(module, edgeInstrumentationSource(input.hosts, own));
  return { module, files, own };
}
